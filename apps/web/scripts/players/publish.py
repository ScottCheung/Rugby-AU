"""Copy framed player photos into public/players/ and write
scripts/seed/playerPhotos.ts. Only players named in a squad are copied.

    python publish.py <framed dir>
"""
import json, pathlib, re, shutil, sys, unicodedata

here = pathlib.Path(__file__).parent
web = here.parent.parent
framed = pathlib.Path(sys.argv[1])
official = json.load(open(here / "official.json"))
squads = (web / "scripts/seed/squads.ts").read_text()

def key(name: str) -> str:
    """Names compared without case, accents, punctuation or spacing."""
    plain = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z]", "", plain.lower())

quoted = re.findall(r"'([A-Z][^'\n]+)'|\"([A-Z][^\"\n]+)\"", squads)
named = {key(single or double) for single, double in quoted}
slug = lambda name: re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")

out = web / "public/players"
shutil.rmtree(out, ignore_errors=True)
entries = {}
for source, page in official.items():
    rows = {}
    for player in page["players"]:
        name = player["name"].strip()
        if not player["photo"] or key(name) not in named:
            continue
        stem = player["photo"].rsplit("/", 1)[1].rsplit(".", 1)[0]
        target = out / source
        target.mkdir(parents=True, exist_ok=True)
        shutil.copy(framed / f"{stem}.webp", target / f"{slug(name)}.webp")
        shutil.copy(framed / f"{stem}-bg.webp", target / f"{slug(name)}-bg.webp")
        rows[key(name)] = {
            "name": name,
            "position": (player["position"] or "").strip() or None,
            "path": f"/players/{source}/{slug(name)}",
        }
    entries[source] = {"url": page["url"], "players": rows}

ts = ["// Generated by scripts/players/publish.py. Do not edit by hand.",
      "",
      "export type PlayerPhoto = { name: string; position: string | null; path: string };",
      "export type PhotoSource = { url: string; players: Record<string, PlayerPhoto> };",
      "",
      f"export const photoSources: Record<string, PhotoSource> = {json.dumps(entries, indent=2)};",
      ""]
(web / "scripts/seed/playerPhotos.ts").write_text("\n".join(ts))
print({k: len(v["players"]) for k, v in entries.items()})
